/**
 * Deterministic synthetic history for the demo students: a year of graded assessments, activity
 * sessions with metrics, goal histories, tasks and upcoming items. Everything is relative to "today"
 * (Asia/Dubai) and generated from a seeded PRNG, so the same day always yields the same data.
 */
import {
  ACTIVITY_KIND_LABELS, ASSESSMENT_KIND_LABELS, enumLabel, type ActivityKind, type ActivitySession, type AssessmentKind,
  type AssessmentResult,
} from '@murshid/core';
import { addDays, dubaiDate, weekday } from '../lib/time';
import type { ActivityDef, DemoProfile, GoalDef, ProjectDef } from './profiles';

/** Days of history generated back from today: a bit over a year so the 12-month "year" charts are full. */
export const HISTORY_DAYS = 400;

// ---------- small utils ----------
export function rng(seed: string): () => number {
  let h = 1779033703 ^ seed.length;
  for (let i = 0; i < seed.length; i++) {
    h = Math.imul(h ^ seed.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export const round = (n: number, d = 0) => Math.round(n * 10 ** d) / 10 ** d;
export const clamp = (n: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, n));
const DAY_MS = 86_400_000;
export const dayDiff = (a: string, b: string) => Math.round((Date.parse(`${b}T00:00:00Z`) - Date.parse(`${a}T00:00:00Z`)) / DAY_MS);
export const mondayOfDate = (date: string) => { const wd = weekday(date); return addDays(date, wd === 0 ? -6 : 1 - wd); };

// ---------- UAE school calendar (approximate, synthetic) ----------
export interface Term { id: string; label: string; start: string; end: string }
export function termsForYear(y: number): Term[] {
  return [
    { id: `${y}-t1`, label: `Term 1 ${y}/${String(y + 1).slice(2)}`, start: `${y}-08-24`, end: `${y}-12-11` },
    { id: `${y}-t2`, label: `Term 2 ${y}/${String(y + 1).slice(2)}`, start: `${y + 1}-01-05`, end: `${y + 1}-03-26` },
    { id: `${y}-t3`, label: `Term 3 ${y}/${String(y + 1).slice(2)}`, start: `${y + 1}-04-13`, end: `${y + 1}-07-02` },
  ];
}
const academicYear = (date: string) => { const y = Number(date.slice(0, 4)); return Number(date.slice(5, 7)) >= 8 ? y : y - 1; };
export const academicYearStart = (date: string) => `${academicYear(date)}-08-24`;
export function isTeachingDay(date: string): boolean {
  const y = academicYear(date);
  return [...termsForYear(y - 1), ...termsForYear(y)].some((t) => date >= t.start && date <= t.end);
}
/** The term containing `date`, or the most recent one that started before it (holidays). */
export function currentTerm(date: string): Term {
  const y = academicYear(date);
  const all = [...termsForYear(y - 1), ...termsForYear(y)].filter((t) => t.start <= date);
  return all[all.length - 1]!;
}

// ---------- generated shapes ----------
export interface DemoTask {
  id: string;
  title: string;
  kind: 'study' | 'assignment' | 'activity' | 'habit' | 'application';
  date: string;
  time: string; // HH:MM Dubai
  durationMinutes: number;
  status: 'todo' | 'done';
  overdue: boolean;
  subjectId: string | null;
  area: string | null;
  /** who created it: generated by the demo engine, an admin, Murshid (agent), or the student */
  source?: 'generated' | 'admin' | 'murshid' | 'student';
  notes?: string | null;
}
export interface ProjectMonth { month: string; revenue: number; orders: number; newCustomers: number; customers: number; followers: number }
export interface GoalState {
  id: string; title: string; titleAr: string; category: GoalDef['category']; unit: string; start: number; target: number;
  better: 'higher' | 'lower'; current: number; progress: number; status: 'active' | 'done'; dueDate: string;
  area: string | null; history: { date: string; value: number }[];
}
export interface DemoData {
  today: string;
  assessments: AssessmentResult[]; // past (graded) and upcoming, ascending by date
  sessions: ActivitySession[]; // ascending
  events: { id: string; activityId: ActivityKind; date: string; title: string }[]; // future scheduled events
  /** monthly metrics per side project (business projects only) */
  projectSeries: Record<string, ProjectMonth[]>;
  /** tasks created by admins / Murshid / the student (merged into the generated daily tasks) */
  customTasks: DemoTask[];
  /** status overrides for generated tasks (by id) */
  taskStatus: Record<string, 'todo' | 'done'>;
  /** generated task ids hidden by an admin */
  hiddenTasks: string[];
}

const KIND_CYCLE: AssessmentKind[] = ['quiz', 'test', 'assignment', 'quiz', 'project'];
const MAX_SCORE: Record<AssessmentKind, number> = { quiz: 20, test: 50, assignment: 25, project: 40, exam: 100 };
const HACK_NAMES = ['Build Weekend', 'Climate Hack', 'AI for Good Jam', 'Smart City Sprint', 'HealthTech Hack', 'Game Jam', 'Space Apps Weekend', 'FinTech Hack'];

function genAssessments(p: DemoProfile, today: string): AssessmentResult[] {
  const out: AssessmentResult[] = [];
  const first = mondayOfDate(addDays(today, -HISTORY_DAYS));
  p.subjects.forEach((s, si) => {
    if (s.generate === false) return;
    const r = rng(`${p.id}:assess:${s.id}`);
    let teachingWeek = 0;
    let n = 0;
    for (let mon = first; mon <= addDays(today, 28); mon = addDays(mon, 7)) {
      const date = addDays(mon, 1 + (si % 4)); // Tue–Fri
      if (!isTeachingDay(date)) continue;
      teachingWeek++;
      if ((teachingWeek + si) % s.every !== 0) continue;
      n++;
      const term = currentTerm(date);
      const examWeek = dayDiff(date, term.end) >= 0 && dayDiff(date, term.end) < 10;
      const mid = addDays(term.start, Math.floor(dayDiff(term.start, term.end) / 2));
      const midWeek = Math.abs(dayDiff(mid, date)) <= 3;
      const kind: AssessmentKind = examWeek || midWeek ? 'exam' : KIND_CYCLE[n % KIND_CYCLE.length]!;
      const unit = Math.max(1, Math.ceil(dayDiff(term.start, date) / 21));
      const title = examWeek ? `${s.name} end-of-term exam` : midWeek ? `${s.name} mid-term exam` : `${s.name} ${ASSESSMENT_KIND_LABELS[kind].en.toLowerCase()} — unit ${unit}`;
      const weeksFromStart = dayDiff(addDays(today, -364), date) / 7;
      const noise = (r() - 0.5) * 11;
      const pct = clamp(s.base + s.slope * weeksFromStart + noise, 30, 99);
      const max = MAX_SCORE[kind];
      const upcoming = date > today;
      const score = upcoming ? null : Math.round((pct / 100) * max);
      out.push({
        id: `${p.id}-${s.id}-a${n}`, subjectId: s.id, title, kind, date, maxScore: max, score,
        percent: score === null ? null : Math.round((score / max) * 100), status: upcoming ? 'upcoming' : 'graded',
      });
    }
  });
  return out.sort((a, b) => a.date.localeCompare(b.date) || a.subjectId.localeCompare(b.subjectId));
}

function metricValues(a: ActivityDef, t: number, r: () => number, keys?: string[]): Record<string, number> {
  const out: Record<string, number> = {};
  for (const m of a.metrics) {
    if (keys && !keys.includes(m.key)) continue;
    if (m.unit === 'goals' || m.unit === 'assists') {
      // per-match counts: mostly 0-1, occasionally 2, rising slightly with form
      const x = r() + clamp(t, 0, 1) * 0.25;
      out[m.key] = x > 1.05 ? 2 : x > (m.unit === 'goals' ? 0.72 : 0.6) ? 1 : 0;
      continue;
    }
    const span = m.end - m.start;
    const v = m.start + span * Math.pow(clamp(t, 0, 1), 0.8) + (r() - 0.5) * Math.abs(span) * 0.12;
    out[m.key] = round(m.unit === 'rank' ? Math.max(1, Math.round(v)) : v, m.decimals);
  }
  return out;
}

function genSessions(p: DemoProfile, today: string): { sessions: ActivitySession[]; events: DemoData['events'] } {
  const sessions: ActivitySession[] = [];
  const events: DemoData['events'] = [];
  const start = addDays(today, -HISTORY_DAYS);
  const t0 = addDays(today, -364);
  const tAt = (d: string) => dayDiff(t0, d) / 364;
  for (const a of p.activities) {
    if (a.generate === false) continue;
    const r = rng(`${p.id}:sessions:${a.id}`);
    const fx = a.fixtures;
    const trainingKeys = a.trainingMetricKeys ?? (fx ? a.metrics.map((m) => m.key).filter((k) => !fx.metricKeys.includes(k)) : undefined);
    if (fx) {
      const fr = rng(`${p.id}:fixtures:${a.id}`);
      let i = 0;
      for (let mon = mondayOfDate(start), w = 0; mon <= addDays(today, 42); mon = addDays(mon, 7), w++) {
        if (w % fx.everyWeeks !== 0) continue;
        const date = addDays(mon, (fx.day + 6) % 7);
        if (date < start) continue;
        if (fx.offMonths?.includes(Number(date.slice(5, 7)))) continue;
        if (fx.everyWeeks === 1 && !isTeachingDay(date)) continue; // school fixtures only in term
        const name = fx.names[i++ % fx.names.length]!;
        const title = fx.kind === 'match' ? `vs ${name}` : name;
        if (date >= today) { events.push({ id: `${p.id}-${a.id}-fx${w}`, activityId: a.id, date, title: fx.kind === 'match' ? `Match ${title}` : title }); continue; }
        const metrics = metricValues(a, tAt(date), fr, fx.metricKeys);
        let note = title;
        if (fx.kind === 'match') {
          const us = Math.max(metrics.goals ?? 0, Math.floor(fr() * 4));
          const them = Math.floor(fr() * 2.6);
          note = `${title}: ${us > them ? 'W' : us === them ? 'D' : 'L'} ${us}-${them}`;
        }
        sessions.push({ id: `${p.id}-${a.id}-${date}-fx`, activityId: a.id, date, minutes: fx.minutes, metrics, note, type: fx.kind });
      }
    }
    if (a.eventEveryWeeks) {
      const offset = Math.floor(r() * a.eventEveryWeeks);
      let i = 0;
      for (let mon = mondayOfDate(start), w = 0; mon <= addDays(today, 70); mon = addDays(mon, 7), w++) {
        if ((w + offset) % a.eventEveryWeeks !== 0) continue;
        const date = addDays(mon, 5); // Saturday
        const title = `${HACK_NAMES[i++ % HACK_NAMES.length]} (Demo)`;
        if (date < start) continue;
        if (date >= today) { events.push({ id: `${p.id}-${a.id}-e${w}`, activityId: a.id, date, title }); continue; }
        const minutes = Math.round((a.minutes * (0.8 + 0.4 * r())) / 30) * 30;
        sessions.push({ id: `${p.id}-${a.id}-${date}`, activityId: a.id, date, minutes, metrics: metricValues(a, tAt(date), r), note: title });
      }
      continue;
    }
    const fixtureDates = new Set(sessions.filter((s) => s.activityId === a.id && s.type).map((s) => s.date));
    for (let d = start; d < today; d = addDays(d, 1)) {
      if (!a.days.includes(weekday(d))) continue;
      const skip = isTeachingDay(d) ? 0.12 : 0.55;
      if (r() < skip) continue;
      const minutes = Math.round((a.minutes * (0.8 + 0.4 * r())) / 5) * 5;
      if (fixtureDates.has(d)) continue; // fixture day replaces training
      sessions.push({ id: `${p.id}-${a.id}-${d}`, activityId: a.id, date: d, minutes, metrics: metricValues(a, tAt(d), r, trainingKeys), note: null });
    }
  }
  sessions.sort((x, y) => x.date.localeCompare(y.date) || x.activityId.localeCompare(y.activityId));
  events.sort((x, y) => x.date.localeCompare(y.date));
  return { sessions, events };
}

/** Monthly revenue / orders / customers for a business project, from its start month to today. */
export function genProjectSeries(proj: ProjectDef, ownerId: string, today: string): ProjectMonth[] {
  if (!proj.growth) return [];
  const g = proj.growth;
  const r = rng(`${ownerId}:project:${proj.id}`);
  const start = addDays(today, proj.startInDays);
  const out: ProjectMonth[] = [];
  let y = Number(start.slice(0, 4));
  let mo = Number(start.slice(5, 7));
  const months: string[] = [];
  while (`${y}-${String(mo).padStart(2, '0')}` <= today.slice(0, 7)) {
    months.push(`${y}-${String(mo).padStart(2, '0')}`);
    mo++; if (mo === 13) { mo = 1; y++; }
  }
  let customers = 0;
  months.forEach((month, i) => {
    const t = months.length > 1 ? i / (months.length - 1) : 1;
    const summer = ['07', '08'].includes(month.slice(5)) ? 0.55 : 1;
    const partial = month === today.slice(0, 7) ? Number(today.slice(8, 10)) / 30 : 1;
    const revenue = Math.round((g.revenueStart + (g.revenueEnd - g.revenueStart) * Math.pow(t, 1.15)) * (0.85 + 0.3 * r()) * summer * partial);
    const orders = Math.max(1, Math.round(revenue / (g.aov * (0.85 + 0.3 * r()))));
    const newCustomers = Math.max(i === 0 ? 1 : 0, Math.round(orders * (1 - g.repeatRate) * (0.8 + 0.4 * r())));
    customers += newCustomers;
    out.push({ month, revenue, orders, newCustomers, customers, followers: Math.round((g.followersEnd ?? 0) * Math.pow(t, 1.3)) });
  });
  return out;
}

export function generateDemoData(p: DemoProfile, today: string): DemoData {
  const { sessions, events } = genSessions(p, today);
  const projectSeries = Object.fromEntries((p.projects ?? []).filter((x) => x.growth).map((x) => [x.id, genProjectSeries(x, p.id, today)]));
  return { today, assessments: genAssessments(p, today), sessions, events, projectSeries, customTasks: [], taskStatus: {}, hiddenTasks: [] };
}

// ---------- derived views ----------
export function subjectScoreAt(assessments: AssessmentResult[], subjectId: string, date: string, n = 3): number | null {
  const graded = assessments.filter((a) => a.subjectId === subjectId && a.percent !== null && a.date <= date);
  if (!graded.length) return null;
  const last = graded.slice(-n);
  return round(last.reduce((s, a) => s + a.percent!, 0) / last.length, 1);
}

export function goalValueAt(g: GoalDef, data: DemoData, sessions: ActivitySession[], date: string): number {
  const s = g.source;
  switch (s.kind) {
    case 'metric': {
      const vals = sessions.filter((x) => x.activityId === s.activity && x.date <= date && typeof x.metrics[s.metric] === 'number').map((x) => x.metrics[s.metric]!);
      if (!vals.length) return g.start;
      return g.better === 'lower' ? Math.min(...vals) : Math.max(...vals);
    }
    case 'subject':
      return subjectScoreAt(data.assessments, s.subject, date) ?? g.start;
    case 'events': {
      const from = academicYearStart(date);
      return sessions.filter((x) => x.activityId === s.activity && x.date >= from && x.date <= date).length;
    }
    case 'weekly-sessions': {
      const from = addDays(date, -27);
      return round(sessions.filter((x) => x.activityId === s.activity && x.date >= from && x.date <= date).length / 4, 1);
    }
    case 'steady': {
      const weeks = Math.max(0, dayDiff(academicYearStart(date), date) / 7);
      return Math.floor(weeks * s.perWeek);
    }
    case 'manual': {
      // linear ramp from start to the recorded current value over the past year (staff-entered goals)
      if (date >= data.today) return s.current;
      const t = clamp(1 - dayDiff(date, data.today) / 364, 0, 1);
      return round(g.start + (s.current - g.start) * t, 1);
    }
    case 'project': {
      const series = data.projectSeries[s.project] ?? [];
      const from = addDays(date, -364).slice(0, 7);
      const xs = series.filter((x) => x.month >= from && x.month <= date.slice(0, 7));
      if (s.metric === 'customers') return xs[xs.length - 1]?.customers ?? 0;
      return xs.reduce((t, x) => t + (s.metric === 'revenue' ? x.revenue : x.orders), 0);
    }
  }
}

export function goalProgress(g: { start: number; target: number; better: 'higher' | 'lower' }, current: number): number {
  const span = g.better === 'higher' ? g.target - g.start : g.start - g.target;
  if (span <= 0) return 100;
  const done = g.better === 'higher' ? current - g.start : g.start - current;
  return Math.round(clamp((done / span) * 100, 0, 100));
}

export function goalStates(p: DemoProfile, data: DemoData, sessions: ActivitySession[]): GoalState[] {
  return p.goals.map((g) => {
    const history: { date: string; value: number }[] = [];
    for (let i = 52; i >= 1; i--) {
      const d = addDays(data.today, -7 * i);
      history.push({ date: d, value: goalValueAt(g, data, sessions, d) });
    }
    const current = goalValueAt(g, data, sessions, data.today);
    history.push({ date: data.today, value: current });
    const progress = goalProgress(g, current);
    const area = g.source.kind === 'subject' ? g.source.subject : 'activity' in g.source ? g.source.activity : g.source.kind === 'project' ? g.source.project : null;
    return {
      id: g.id, title: g.title, titleAr: g.titleAr, category: g.category, unit: g.unit, start: g.start, target: g.target,
      better: g.better, current, progress, status: progress >= 100 ? 'done' : 'active', dueDate: addDays(data.today, g.dueInDays),
      area, history,
    };
  });
}

const hm = (s: string) => Number(s.slice(0, 2)) * 60 + Number(s.slice(3, 5));

/** Tasks for one day (homework Mon–Fri, scheduled activities, revision before assessments). */
export function tasksForDay(p: DemoProfile, data: DemoData, date: string, now: Date): DemoTask[] {
  const wd = weekday(date);
  const out: DemoTask[] = [];
  const dayNo = dayDiff('2026-01-01', date);
  const short = p.band === 'g5-6';
  if (wd >= 1 && wd <= 5 && p.subjects.length) {
    const s = p.subjects[((dayNo % p.subjects.length) + p.subjects.length) % p.subjects.length]!;
    out.push({ id: `task-${date}-hw-${s.id}`, title: `${s.name} homework`, kind: 'assignment', date, time: '16:30', durationMinutes: short ? 20 : 40, status: 'todo', overdue: false, subjectId: s.id, area: s.id });
  }
  for (const a of p.activities) {
    if (!a.days.includes(wd)) continue;
    out.push({ id: `task-${date}-act-${a.id}`, title: `${ACTIVITY_KIND_LABELS[a.id].en}: ${a.detail}`, kind: 'activity', date, time: '17:30', durationMinutes: a.minutes, status: 'todo', overdue: false, subjectId: null, area: a.id });
  }
  for (const ev of data.events.filter((e) => e.date === date)) {
    out.push({ id: `task-${date}-event-${ev.id}`, title: ev.title, kind: 'activity', date, time: '09:00', durationMinutes: 480, status: 'todo', overdue: false, subjectId: null, area: ev.activityId });
  }
  const soon = data.assessments.filter((x) => { const dd = dayDiff(date, x.date); return dd >= 1 && dd <= 3; });
  for (const x of soon.slice(0, 2)) {
    const s = p.subjects.find((y) => y.id === x.subjectId);
    if (!s) continue;
    out.push({ id: `task-${date}-rev-${x.id}`, title: `Revise for ${s.name} ${ASSESSMENT_KIND_LABELS[x.kind].en.toLowerCase()}`, kind: 'study', date, time: '19:00', durationMinutes: x.kind === 'exam' ? 60 : short ? 20 : 35, status: 'todo', overdue: false, subjectId: s.id, area: s.id });
  }
  if (short) out.push({ id: `task-${date}-read`, title: 'Read for 20 minutes', kind: 'habit', date, time: '20:00', durationMinutes: 20, status: 'todo', overdue: false, subjectId: 'english', area: 'goal-reading' });

  const nowDate = dubaiDate(now);
  const nowMin = Math.floor(((now.getTime() + 4 * 3_600_000) % DAY_MS) / 60_000);
  for (const t of out) {
    t.source = 'generated';
    if (date < nowDate) t.status = 'done';
    else if (date === nowDate && hm(t.time) + t.durationMinutes <= nowMin) t.status = 'done';
  }
  const hidden = new Set(data.hiddenTasks ?? []);
  const merged = [...out.filter((t) => !hidden.has(t.id)), ...(data.customTasks ?? []).filter((t) => t.date === date).map((t) => ({ ...t }))];
  for (const t of merged) {
    const st = data.taskStatus?.[t.id];
    if (st) t.status = st;
    // custom tasks keep their own status; past open ones are overdue
    if (t.source !== 'generated') t.overdue = t.status === 'todo' && date < nowDate;
  }
  return merged.sort((a, b) => a.time.localeCompare(b.time));
}

/** Tasks from `fromOffset` to `toOffset` days around today; the latest past homework of older students stays open (overdue). */
export function tasksRange(p: DemoProfile, data: DemoData, now: Date, fromOffset: number, toOffset: number): DemoTask[] {
  const out: DemoTask[] = [];
  for (let i = fromOffset; i <= toOffset; i++) out.push(...tasksForDay(p, data, addDays(data.today, i), now));
  if (p.grade >= 9) {
    const past = tasksRange0(p, data, now).filter((t) => t.kind === 'assignment');
    const last = past[past.length - 1];
    const hit = last && out.find((t) => t.id === last.id);
    if (hit && data.taskStatus?.[hit.id] !== 'done') { hit.status = 'todo'; hit.overdue = true; }
  }
  return out;
}
function tasksRange0(p: DemoProfile, data: DemoData, now: Date): DemoTask[] {
  const out: DemoTask[] = [];
  for (let i = -3; i <= -1; i++) out.push(...tasksForDay(p, data, addDays(data.today, i), now));
  return out;
}

export function overdueTasks(p: DemoProfile, data: DemoData, now: Date): DemoTask[] {
  const recent = tasksRange(p, data, now, -3, -1).filter((t) => t.overdue);
  const older = (data.customTasks ?? []).filter((t) => t.date < addDays(data.today, -3) && (data.taskStatus?.[t.id] ?? t.status) === 'todo')
    .map((t) => ({ ...t, overdue: true }));
  return [...older, ...recent];
}

