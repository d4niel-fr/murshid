'use client';

import Link from 'next/link';
import { motion } from 'motion/react';
import { ArrowUpRight, Sparkles } from 'lucide-react';
import type { ReactNode } from 'react';
import { useApp } from '@/components/providers/app-provider';
import { Segmented } from '@/components/ui/segmented';
import { messageIn } from '@/lib/motion';
import type { ChartRange, ChartSpec } from '@/lib/types';
import { cn } from '@/lib/utils';
import { ChartView } from './chart-view';

export function RangeToggle({ value, onChange, allowed }: { value: ChartRange; onChange: (r: ChartRange) => void; allowed?: ChartRange[] }) {
  const { t } = useApp();
  const all: ChartRange[] = allowed ?? ['4w', '12w', 'term', 'year'];
  return <Segmented size="sm" value={value} onChange={onChange} ariaLabel="Range" options={all.map((r) => ({ value: r, label: t(`range.${r}` as const) }))} />;
}

/** ChartCard anatomy (DESIGN §8): eyebrow title → insight → subtitle → chart → legend → footer. */
export function ChartCard({ spec, height = 220, range, onRange, allowedRanges, actions, footerLink, className, inline }: {
  spec: ChartSpec; height?: number; range?: ChartRange; onRange?: (r: ChartRange) => void; allowedRanges?: ChartRange[];
  actions?: ReactNode; footerLink?: { href: string; label: string }; className?: string; inline?: boolean;
}) {
  const { dir, tx } = useApp();
  return (
    <motion.div {...(inline ? messageIn : {})} className={cn('card p-5', className)}>
      <div className="mb-1 flex items-start justify-between gap-3">
        <p className="card-title pt-1">{spec.title}</p>
        <div className="flex items-center gap-2">
          {actions}
          {range && onRange && <RangeToggle value={range} onChange={onRange} allowed={allowedRanges} />}
        </div>
      </div>
      <p className="max-w-[60ch] text-base font-semibold leading-snug">{spec.insight}</p>
      {spec.subtitle && <p className="mt-1 text-xs text-muted-foreground">{spec.subtitle}</p>}
      <div className="mt-4">
        <ChartView spec={spec} height={height} rtl={dir === 'rtl'} />
      </div>
      <div className="mt-3 flex items-center justify-between text-2xs text-muted-foreground">
        <span className="inline-flex items-center gap-1"><Sparkles className="size-3" />{spec.generatedBy === 'ai' ? tx('Generated by AI', 'أنشأه الذكاء الاصطناعي') : tx('Generated by rules from your data', 'أُنشئ بالقواعد من بياناتك')}</span>
        {footerLink && (
          <Link href={footerLink.href} className="inline-flex items-center gap-0.5 font-medium text-foreground hover:text-primary">
            {footerLink.label}<ArrowUpRight className="size-3 rtl:-scale-x-100" />
          </Link>
        )}
      </div>
    </motion.div>
  );
}
